import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

// logo.svg owns the geometry. Inline copies avoid page URL/CSP dependencies.
const directory = '.agents/skills/chippy/extension';
const source = readFileSync(`${directory}/logo.svg`, 'utf8').trim();
const mark = source.replace('<svg ', '<svg data-chippy-logo aria-hidden="true" width="24" height="24" ');
const layoutPath = `${directory}/layout-lab.js`;
const layout = readFileSync(layoutPath, 'utf8');
const declaration = `  const CHIPPY_LOGO = ${JSON.stringify(mark)};`;
writeFileSync(layoutPath, layout.replace(/^  const CHIPPY_LOGO = .*;$/m, declaration));
writeFileSync('.storybook/chippy-addon/brand.jsx', `// Generated by scripts/sync-chippy-brand.mjs from extension/logo.svg.\nimport React from 'react';\n\nexport function ChippyLogo() {\n  return <span style={{ display: 'inline-flex' }} dangerouslySetInnerHTML={{ __html: ${JSON.stringify(mark)} }} />;\n}\n`);
const browser = await chromium.launch({ headless: true });
try {
  for (const size of [16, 32, 48, 128]) {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    await page.setContent(`<style>body{margin:0}svg{width:100%;height:100%;display:block}</style>${source}`);
    await page.screenshot({ path: `${directory}/icon-${size}.png`, omitBackground: true, animations: 'disabled' });
    await page.close();
  }
} finally {
  await browser.close();
}
